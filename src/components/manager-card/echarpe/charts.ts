/**
 * The knit charts: every glyph the scarf knits, hand-cleaned stitch by stitch on an integer grid
 * ('#' is a stitch, '.' is not). Ported unchanged from the lab's Écharpe v2 (see README.md).
 * Data only.
 *
 * Digits are drawn from Changa 800: 9 stitches by 13 rows with three-stitch stems, two-row bars
 * and open three-stitch counters. Latin capitals are two-stitch stems on 8 rows, with condensed
 * 7- and 6-row sets for names that need to fit. Tier words are one-stitch strokes on 4 rows.
 * Arabic charts are in visual order (left to right on the page) and are never mirrored.
 */

/** A font of charts: each glyph is a list of equal-length rows. */
export type Font = Readonly<Record<string, readonly string[]>>;
/** An Arabic chart: the rows in visual order, and the last row of the two-row baseline. */
export interface ArabicChart {
  readonly base: number;
  readonly bmp: readonly string[];
}

